"""Build data/speak.json from tools/content/*.py (one unit per file).
Edit the unit files, then run:  python3 tools/build_content.py
"""
import json, os, sys, importlib
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "content"))
ORDER = ["f1", "f2", "f3", "f4", "f5", "f6", "f7", "g1", "g2", "g3", "g4", "g5"]
TRACKS = [
 {"id": "family", "title": "Family", "jpTitle": "かぞくとはなそう", "blurb": "Warm catch-ups with family she already knows: door hellos, dinner, teasing Shota, video calls."},
 {"id": "around", "title": "Getting around", "jpTitle": "まちで", "blurb": "Cafés, trains, shops, konbini, and asking for help."},
]
def clean(o):
    if isinstance(o, dict):
        o = {k: clean(v) for k, v in o.items()}
        if o.get("kana") and o.get("jp") and o["kana"] == o["jp"]:
            del o["kana"]
        return o
    if isinstance(o, list):
        return [clean(x) for x in o]
    return o
units = []
for m in ORDER:
    units += importlib.import_module(m).units
units = clean(units)
# fix-ups
for u in units:
    for it in u["listening"]:
        for op in it["reply"]["options"]:
            if op["jp"] == "右ですね。": op["en"] = "To the right, then?"
errs = []
ids = set()
for u in units:
    assert u["id"] not in ids; ids.add(u["id"])
    assert u["track"] in ("family", "around")
    for p in u["phrases"]:
        for k in ("jp", "romaji", "en"):
            if not p.get(k): errs.append((u["id"], k, p))
    for ln in u["roleplay"]["lines"]:
        if ln["speaker"] == "you":
            if len(ln["options"]) < 2: errs.append((u["id"], "opts", ln))
            if len({o["jp"] for o in ln["options"]}) != len(ln["options"]): errs.append((u["id"], "dup", ln))
    if len(u["listening"]) < 3: errs.append((u["id"], "listening"))
    for it in u["listening"]:
        if len(it["meanings"]) < 3: errs.append((u["id"], "meanings", it["jp"]))
if errs:
    print("ERRORS", errs); sys.exit(1)
out = {
 "_readme": "Generated by tools/build_content.py from tools/content/*.py. Each unit: phrases (jp, kana reading if it differs, romaji, en, note, grammar), roleplay lines (them / you with options, first option correct), listening items (meanings and reply options, first correct; the app shuffles).",
 "tracks": TRACKS, "units": units}
path = os.path.join(HERE, "..", "data", "speak.json")
json.dump(out, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
for t in TRACKS:
    print(t["title"]); [print("  ", u["id"], u["title"], len(u["phrases"]), "phrases") for u in units if u["track"] == t["id"]]
